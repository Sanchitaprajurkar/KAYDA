# 4. CROSS EXAMINATION (ATTACKS & DEFENCES)
# ============================================================

class AttackReason(str, Enum):
    CONTRADICTS = "contradicts"     # Opponent's claim directly contradicts higher-tier or official data
    RETRACTED = "retracted"         # Opponent cited a bulletin or article that has been formally retracted
    LOW_TIER = "low_tier"           # Opponent relied on Tier 4 tabloid/social rumour without official corroboration
    WRONG_SCOPE = "wrong_scope"     # Evidence from an unrelated sector/country misapplied to this commercial flow
    STALE = "stale"                 # Outdated pre-disruption assumptions superseded by subsequent events
    MATH_ERROR = "math_error"       # Gross vs net confusion, baseline mismatch, or mathematical fabrication

class CrossExamAttack(BaseModel):
    """
    Structured attack launched during cross-examination against an opponent's claim.
    """
    attack_id: str = Field(..., description="Unique attack identifier, e.g. ATK-TH-01")
    target_claim_id: str = Field(..., description="Target claim being challenged, e.g. LK-01")
    attacker_agent: str = Field("THOR", description="Attacking agent (THOR or LOKI)")
    target_agent: str = Field("LOKI", description="Agent defending the claim")
    reason: AttackReason = Field(..., description="Categorical attack basis")
    counter_evidence: List[Citation] = Field(
        default_factory=list,
        description="Citations supporting the attack"
    )
    argument: str = Field(..., description="Detailed argument exposing the defect in the target claim")
    created_at: Optional[str] = Field(default_factory=lambda: datetime.utcnow().isoformat())

class ResponseDecision(str, Enum):
    DEFENDED = "DEFENDED"     # Claim defended by introducing NEW evidence not previously cited
    CONCEDED = "CONCEDED"     # Evidence defeats the claim; Thor formally concedes to preserve judicial integrity
    MAINTAINED = "MAINTAINED" # Attack was unsubstantiated or based on invalid grounds; claim stands

class CrossExamResponse(BaseModel):
    """
    Structured defence or concession in response to an opponent's attack.
    """
    response_id: str = Field(..., description="Unique response identifier, e.g. RES-TH-01")
    attack_id: str = Field(..., description="Attack identifier being answered")
    claim_id: str = Field(..., description="Claim identifier being defended or conceded")
    target_agent: str = Field("THOR", description="Responding agent")
    decision: ResponseDecision = Field(..., description="DEFENDED, CONCEDED, or MAINTAINED")
    defence_evidence: List[Citation] = Field(
        default_factory=list,
        description="NEW evidence not previously used (mandatory if DEFENDED)"
    )
    explanation: str = Field(..., description="Detailed justification of defence or reason for concession")
    concession_impact: Optional[str] = Field(None, description="Analytical impact on exposure range if conceded")
    memory_influence: Optional[str] = Field(None, description="How private memory influenced this response decision")
    created_at: Optional[str] = Field(default_factory=lambda: datetime.utcnow().isoformat())

