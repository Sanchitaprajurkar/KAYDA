class SearchFilter(BaseModel):
    event_id: Optional[str] = None
    country: Optional[str] = None
    sector: Optional[str] = None
    source_type: Optional[Union[str, List[str]]] = None
    min_reliability: Optional[int] = None
    max_reliability: Optional[int] = None
    as_of_date: str = Field(..., description="Strict clock cutoff date (YYYY-MM-DD)")
    exclude_retracted: bool = True

class SearchResult(BaseModel):
    doc_id: str
    title: str
    source_name: str
    source_type: str
    reliability: int
    pub_date: str
    country: str
    sector: str
    event_id: str
    excerpt: str
    score: float = 1.0
    is_retracted: bool = False
    matched_terms: List[str] = Field(default_factory=list)

class MemoryAction(str, Enum):
    READ = "READ"
    WRITE = "WRITE"

class MemoryCategory(str, Enum):
    OPPONENT_PROFILE = "OPPONENT_PROFILE"
    VERIFIED_CORRIDOR_LIMITS = "VERIFIED_CORRIDOR_LIMITS"
    RETRACTED_SOURCES = "RETRACTED_SOURCES"
    DISRUPTION_BASELINES = "DISRUPTION_BASELINES"
    CONCESSIONS_HISTORY = "CONCESSIONS_HISTORY"
    COVERAGE_GAPS = "COVERAGE_GAPS"
    PRIOR_CLAIMS = "PRIOR_CLAIMS"
    EVIDENCE_INVENTORY = "EVIDENCE_INVENTORY"

class MemoryEntry(BaseModel):
    key: str
    category: MemoryCategory
    value: Any
    source: str
    confidence: float = 1.0
    created_at: str
    last_accessed: str

class MemoryLog(BaseModel):
    action: MemoryAction
    key: str
    category: Optional[str] = None
    context: str
    decision_influence: str
    timestamp: str
