from typing import List, Optional, Union, Any, Dict
from enum import Enum
from datetime import datetime
from pydantic import BaseModel, Field

# ============================================================
# 1. CITATIONS & GROUNDING
# ============================================================

class Citation(BaseModel):
    """
    Traceable citation linking a finding to an exact document and paragraph/row in Runemark.
    """
    doc_id: str = Field(..., description="Document ID from manifest (e.g. ORV-0009)")
    paragraph_or_row_id: Optional[str] = Field(None, description="Paragraph ID (e.g. P2, P8) or Table Row ID")
    source_name: Optional[str] = Field(None, description="Publishing outlet or authority name")
    reliability_tier: int = Field(..., ge=1, le=4, description="1 (Official) to 4 (Weak)")
    pub_date: str = Field(..., description="Publication date YYYY-MM-DD")
    title: Optional[str] = Field(None, description="Document title")
    excerpt: str = Field(..., description="Exact textual excerpt or data quote")
    verified: bool = Field(True, description="Whether citation was validated against manifest and corpus text")

class CitationValidationReport(BaseModel):
    """
    Validation report verifying a citation against manifest, clock, retractions, and contents.
    """
    is_valid: bool = Field(..., description="Whether the citation passed all validation gates")
    doc_id: str = Field(..., description="Document ID being validated")
    exists_in_manifest: bool = Field(..., description="Found in Runemark manifest.json")
    is_clock_compliant: bool = Field(..., description="pub_date <= as_of_date (no future data leakage)")
    is_retracted: bool = Field(..., description="Whether source was retracted or superseded")
    reliability_tier: Optional[int] = Field(None, description="Verified tier from manifest")
    content_matched: bool = Field(..., description="Whether excerpt actually exists in the source text")
    errors: List[str] = Field(default_factory=list, description="Validation failure reasons")
    warnings: List[str] = Field(default_factory=list, description="Non-fatal warnings (e.g. Tier 4 usage)")

# ============================================================
# 2. HIGH EXPOSURE CLAIMS & EVIDENCE GAPS
# ============================================================

class ClaimClassification(str, Enum):
    FACT = "FACT"             # Directly stated in Tier 1 or Tier 2 official/reputable documents
    INFERENCE = "INFERENCE"   # Derived via quantitative trade model, baseline delta, or analytical synthesis

class ClaimStatus(str, Enum):
    ACTIVE = "ACTIVE"
    CONTESTED = "CONTESTED"
    DEFENDED = "DEFENDED"
    CONCEDED = "CONCEDED"

class ClaimEstimate(BaseModel):
    low_bound: float = Field(..., description="Lower limit of exposure estimate")
    high_bound: float = Field(..., description="Upper limit of exposure estimate")
    unit: str = Field(..., description="Unit of measurement, e.g. USD_millions, metric_tonnes, pct")
    formatted: str = Field(..., description="Human-readable range, e.g. '$197.6M — $216.2M'")

class HighExposureClaim(BaseModel):
    """
    Structured claim generated by Thor asserting high commercial exposure.
    """
    claim_id: str = Field(..., description="Claim identifier, e.g. TH-01")
    agent: str = Field("THOR", description="Originating agent name")
    round: int = Field(1, description="Trial round number when claim was authored")
    country: str = Field(..., description="Target country")
    sector: str = Field(..., description="Target sector")
    statement: str = Field(..., description="Explicit, unambiguous commercial exposure assertion")
    estimate: ClaimEstimate = Field(..., description="Quantitative low and high exposure bounds")
    metric: str = Field(..., description="Metric description, e.g. 'Trade Value Disruption (USD M)'")
    baseline: str = Field(..., description="Explicit comparative baseline with period and source")
    reasoning: str = Field(..., description="Step-by-step logic detailing why exposure is severe")
    classification: ClaimClassification = Field(..., description="FACT vs INFERENCE")
    citations: List[Citation] = Field(..., min_length=1, description="Traceable citations supporting the claim")
    status: ClaimStatus = Field(ClaimStatus.ACTIVE, description="Current courtroom status")
    concession_note: Optional[str] = Field(None, description="Explanation if conceded during cross-examination")
    created_at: Optional[str] = Field(default_factory=lambda: datetime.utcnow().isoformat())

class EvidenceGapStatus(BaseModel):
    """
    Explicit status returned when data is missing, preventing range fabrication.
    """
    country: str = Field(..., description="Country with missing data")
    sector: str = Field(..., description="Sector with missing data")
    status: str = Field("EVIDENCE_GAP", description="Explicit EVIDENCE_GAP flag")
    statement: str = Field(..., description="Formal declaration of evidence insufficiency")
    gap_reason: str = Field(..., description="Detailed explanation of what data is missing from Runemark")
    impact_on_exposure: str = Field(..., description="Why fabricating a range is prohibited and how gap is handled")

# ============================================================
# 3. DETERMINISTIC TRADE CALCULATIONS
# ============================================================

class TradeRow(BaseModel):
    """
    Validated single trade observation row parsed from a trade table or trade note.
    """
    doc_id: str = Field(..., description="Source document ID, e.g. ORV-0009")
    row_id: str = Field(..., description="Paragraph/row identifier, e.g. P2")
    full_id: str = Field(..., description="Compound ID, e.g. ORV-0009#P2")
    country_from: Optional[str] = Field(None, description="Exporter country")
    country_to: Optional[str] = Field(None, description="Importer country")
    sector: str = Field(..., description="Commodity sector, e.g. Wheat, Maize")
    month: str = Field(..., description="Month name, e.g. September")
    year: int = Field(..., description="Calendar year, e.g. 2026")
    period: str = Field(..., description="Normalized period, e.g. 2026-09")
    val_usd_m: float = Field(..., ge=0.0, description="Trade value in USD Millions")
    vol_tonnes: float = Field(..., ge=0.0, description="Trade volume in metric tonnes")
    is_damaged: bool = Field(False, description="Whether the row was corrupted or incomplete")
    damage_reason: Optional[str] = Field(None, description="Details if row was damaged")

class DisruptionCalculationInput(BaseModel):
    """
    Inputs required for deterministic gross and net disruption calculation.
    """
    country: str = Field(..., description="Importer country under analysis")
    sector: str = Field(..., description="Sector under analysis")
    primary_supplier: str = Field(..., description="Disrupted primary supplier, e.g. Orvan")
    primary_rows: List[TradeRow] = Field(..., description="Monthly trade rows for primary supplier")
    substitute_suppliers: List[str] = Field(default_factory=list, description="Evidenced substitute suppliers, e.g. Vanir")
    substitute_rows: List[TradeRow] = Field(default_factory=list, description="Monthly trade rows for substitute suppliers")
    baseline_year: int = Field(2025, description="Pre-disruption comparison year")
    disrupted_year: int = Field(2026, description="Disrupted year")
    disruption_months: List[str] = Field(
        default=["September", "October", "November", "December"],
        description="Months affected by disruption"
    )
    spot_price_escalation_pct: float = Field(
        default=0.0,
        ge=0.0,
        description="Spot/forward price escalation percentage (e.g. 18.0 for 18% forward repricing)"
    )

class DisruptionCalculationResult(BaseModel):
    """
    Deterministic quantitative result of disruption calculations outside the LLM.
    """
    country: str = Field(..., description="Importer country")
    sector: str = Field(..., description="Commodity sector")
    baseline_value_usd_m: float = Field(..., description="Baseline trade value (USD M)")
    baseline_volume_tonnes: float = Field(..., description="Baseline trade volume (tonnes)")
    disrupted_value_usd_m: float = Field(..., description="Disrupted trade value (USD M)")
    disrupted_volume_tonnes: float = Field(..., description="Disrupted trade volume (tonnes)")
    
    # Gross Supplier Disruption
    gross_value_loss_usd_m: float = Field(..., description="Gross supplier value decline (USD M)")
    gross_volume_loss_tonnes: float = Field(..., description="Gross supplier volume decline (tonnes)")
    gross_value_loss_pct: float = Field(..., description="Gross value drop percentage")
    gross_volume_loss_pct: float = Field(..., description="Gross volume drop percentage")
    
    # Evidenced Substitute Supply
    substitute_value_gain_usd_m: float = Field(0.0, description="Evidenced substitute supply value gain (USD M)")
    substitute_volume_gain_tonnes: float = Field(0.0, description="Evidenced substitute supply volume gain (tonnes)")
    
    # Net Disruption
    net_value_loss_usd_m: float = Field(..., description="Net value decline after substitute supply (USD M)")
    net_volume_loss_tonnes: float = Field(..., description="Net volume decline after substitute supply (tonnes)")
    net_value_loss_pct: float = Field(..., description="Net value drop percentage relative to baseline")
    net_volume_loss_pct: float = Field(..., description="Net volume drop percentage relative to baseline")
    
    # Analytical Bounds for Thor
    high_exposure_bound_usd_m: float = Field(..., description="Thor high exposure bound (Gross loss or price-adjusted)")
    low_exposure_bound_usd_m: float = Field(..., description="Thor low exposure bound (Net loss after verified substitutes)")
    
    # Traceability
    source_row_ids: List[str] = Field(default_factory=list, description="IDs of all primary rows used")
    substitute_row_ids: List[str] = Field(default_factory=list, description="IDs of all substitute rows used")
    damaged_rows_reported: List[str] = Field(default_factory=list, description="IDs of any damaged or rejected rows")
    calculation_notes: List[str] = Field(default_factory=list, description="Explanatory notes and methodology")

